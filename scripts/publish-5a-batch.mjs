/**
 * US News Engine — Phase 5A batch article publisher.
 *
 * Takes 5 generated drafts, applies the correct image strategy (real photo
 * or map), creates public Astro content collection article files, and
 * updates each draft's image metadata.
 *
 * Usage:
 *   node scripts/publish-5a-batch.mjs
 */

import { readFile, writeFile, mkdir, unlink, copyFile, readdir } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const PROJECT_DIR = join(__dirname, '..');
const DRAFTS_DIR = join(PROJECT_DIR, 'data', 'drafts');
const DRAFT_IMAGES_DIR = join(PROJECT_DIR, 'data', 'draft-images');
const PUBLIC_IMAGES_DIR = join(PROJECT_DIR, 'public', 'images');
const ARTICLES_DIR = join(PROJECT_DIR, 'src', 'content', 'articles');

// The 5 selected stories with their image strategy
const STORIES = [
  {
    storyKey: 'flood-warning__lake-il__2026-09-27',
    heroMode: 'licensed-photo', // real photo
    heroRelation: 'exact-location',
    secondaryMap: true,
  },
  {
    storyKey: 'flood-warning__lake-fl__2026-09-27',
    heroMode: 'licensed-photo', // real photo
    heroRelation: 'exact-location',
    secondaryMap: true,
  },
  {
    storyKey: 'coastal-flood-warning__surry__2026-09-27',
    heroMode: 'map-data', // map fallback (no relevant real photo)
    heroRelation: 'current-alert-data',
    secondaryMap: false, // map IS the hero
  },
  {
    storyKey: 'high-wind-warning__lanai-mauka__2026-09-27',
    heroMode: 'map-data', // map fallback
    heroRelation: 'current-alert-data',
    secondaryMap: false,
  },
  {
    storyKey: 'flood-warning__bristol-ma__2026-09-27',
    heroMode: 'map-data', // map fallback
    heroRelation: 'current-alert-data',
    secondaryMap: false,
  },
];

async function main() {
  console.log('[publish-5a] Starting batch article publication.');

  // Ensure public images directory exists
  await mkdir(PUBLIC_IMAGES_DIR, { recursive: true });

  for (const config of STORIES) {
    console.log(`\n--- Processing ${config.storyKey} ---`);
    const draftPath = join(DRAFTS_DIR, `${config.storyKey}.json`);
    const draft = JSON.parse(await readFile(draftPath, 'utf8'));
    const slug = draft.slug;

    // --- Determine hero image path ---
    let heroImagePath;
    let heroImageAlt;
    let heroImageCaption;
    let heroAttribution = null;

    if (config.heroMode === 'licensed-photo') {
      // Use the real photo
      const realPhotoPath = join(DRAFT_IMAGES_DIR, `${slug}-real.jpg`);
      const publicPhotoPath = join(PUBLIC_IMAGES_DIR, `${slug}-real.jpg`);
      await copyFile(realPhotoPath, publicPhotoPath);
      heroImagePath = `/images/${slug}-real.jpg`;

      // Load real photo metadata
      const realMetaPath = join(DRAFT_IMAGES_DIR, `${slug}-real.json`);
      const realMeta = JSON.parse(await readFile(realMetaPath, 'utf8'));
      heroImageAlt = realMeta.alt;
      heroImageCaption = realMeta.caption;
      heroAttribution = realMeta.attributionText || `Photo: ${realMeta.creator} / ${realMeta.license}`;

      // Update draft with hero image metadata
      draft.heroImage = {
        mode: 'licensed-photo',
        relation: 'exact-location',
        path: heroImagePath,
        alt: heroImageAlt,
        caption: heroImageCaption,
        creator: realMeta.creator,
        license: realMeta.license,
        licenseUrl: realMeta.licenseUrl,
        sourcePageUrl: realMeta.sourcePageUrl,
        originalDate: realMeta.originalDate,
        attributionRequired: realMeta.attributionRequired,
        attributionText: heroAttribution,
      };
    } else {
      // Use the map as hero
      const mapPath = join(DRAFT_IMAGES_DIR, `${slug}-map.png`);
      const publicMapPath = join(PUBLIC_IMAGES_DIR, `${slug}-map.png`);
      await copyFile(mapPath, publicMapPath);
      heroImagePath = `/images/${slug}-map.png`;
      heroImageAlt = `${draft.weatherMetadata.event} map for ${draft.location}.`;
      heroImageCaption = `National Weather Service alert area for ${draft.location}. Map: US News Engine using NWS geographic data.`;

      draft.heroImage = {
        mode: 'map-data',
        relation: 'current-alert-data',
        path: heroImagePath,
        alt: heroImageAlt,
        caption: heroImageCaption,
        creator: 'US News Engine',
        license: 'Original graphic generated by US News Engine from factual NWS data',
        licenseUrl: '',
        sourcePageUrl: '',
        originalDate: '',
        attributionRequired: false,
        attributionText: 'Map: US News Engine / NWS data',
      };
    }

    // --- Secondary map (only when hero is a real photo) ---
    if (config.secondaryMap) {
      const mapPath = join(DRAFT_IMAGES_DIR, `${slug}-map.png`);
      const publicMapPath = join(PUBLIC_IMAGES_DIR, `${slug}-map.png`);
      await copyFile(mapPath, publicMapPath);
      draft.secondaryImage = {
        mode: 'map-data',
        relation: 'current-alert-data',
        path: `/images/${slug}-map.png`,
        alt: `${draft.weatherMetadata.event} alert area map for ${draft.location}.`,
        caption: `National Weather Service alert area for ${draft.location}.`,
        source: 'US News Engine',
        dataSource: 'National Weather Service',
        geographicDataSource: 'NWS alert geometry + NWS zone boundaries + public-domain state outline',
        attributionText: 'Map: US News Engine using NWS geographic data',
      };
    } else {
      draft.secondaryImage = null;
    }

    // --- Set publication timestamps ---
    // First publication: publishedAt = now, updatedAt = null
    const now = new Date().toISOString();
    if (!draft.publishedAt || draft.publishedAt === draft.generatedAt) {
      draft.publishedAt = now;
    }
    draft.updatedAt = null;
    draft.draftVersion = (draft.draftVersion || 1) + 1;

    // --- Save updated draft ---
    await writeFile(draftPath, JSON.stringify(draft, null, 2) + '\n', 'utf8');
    console.log(`  Draft updated: ${draftPath}`);

    // --- Create public article markdown file ---
    const articlePath = join(ARTICLES_DIR, `${slug}.md`);
    const articleContent = buildArticleMarkdown(draft, config);
    await writeFile(articlePath, articleContent, 'utf8');
    console.log(`  Article created: ${articlePath}`);

    console.log(`  Hero: ${config.heroMode} (${heroImagePath})`);
    console.log(`  Secondary map: ${config.secondaryMap ? 'yes' : 'no'}`);
  }

  // --- Remove fictional demo articles ---
  console.log('\n--- Removing fictional demo articles ---');
  const articleFiles = await readdir(ARTICLES_DIR);
  const demoSlugs = [
    'senate-advances-bipartisan-infrastructure-measure',
    'severe-storm-system-sweeps-midwest-tornado-watches',
    'manufacturer-recalls-48000-electric-vehicles-battery-defect',
    'ftc-proposes-rules-cracking-down-on-hidden-subscription-fees',
    'nasa-mission-returns-first-close-images-of-distant-asteroid',
    'texas-lawmakers-debate-grid-modernization-ahead-of-summer-demand',
    'grocery-prices-ease-for-third-straight-month-economists-say',
    'western-heat-dome-breaks-records-across-four-states',
    'researchers-identify-gene-linked-to-heat-tolerance-in-crops',
    'national-frozen-vegetables-recalled-over-listeria-concerns',
  ];
  let removedCount = 0;
  for (const file of articleFiles) {
    const baseName = file.replace(/\.md$/, '');
    if (demoSlugs.includes(baseName)) {
      await unlink(join(ARTICLES_DIR, file));
      console.log(`  Removed: ${file}`);
      removedCount++;
    }
  }
  console.log(`  Total demo articles removed: ${removedCount}`);

  // Verify remaining articles
  const remaining = await readdir(ARTICLES_DIR);
  console.log(`  Remaining articles: ${remaining.length}`);
  for (const f of remaining) {
    console.log(`    - ${f}`);
  }

  console.log('\n[publish-5a] Done.');
}

/**
 * Build a markdown article file from a draft, matching the Astro content
 * collection schema (src/content.config.ts).
 */
function buildArticleMarkdown(draft, config) {
  const w = draft.weatherMetadata;
  const heroPath = draft.heroImage.path;
  const heroAlt = draft.heroImage.alt;

  // Build body markdown from draft sections
  const bodyMarkdown = draft.body
    .map((section) => {
      const heading = section.heading ? `\n## ${section.heading}\n` : '';
      const paras = section.paragraphs.join('\n\n');
      return heading + paras;
    })
    .join('\n\n');

  // Insert secondary map after "Areas affected" if present
  let finalBody = bodyMarkdown;
  if (draft.secondaryImage) {
    const mapMarkdown = `\n\n![${draft.secondaryImage.alt}](${draft.secondaryImage.path})\n\n*${draft.secondaryImage.caption} ${draft.secondaryImage.attributionText}.*\n`;
    finalBody = finalBody.replace(
      /## Areas affected[\s\S]*?(?=\n## |$)/,
      (match) => match + mapMarkdown,
    );
  }

  // Format dates for frontmatter (ISO)
  const publishedAt = draft.publishedAt;
  const updatedAt = draft.updatedAt || publishedAt; // Astro schema requires a date; use publishedAt if null

  // Tags from weather metadata
  const tags = [
    draft.weatherMetadata.event,
    'Weather',
    draft.weatherMetadata.severity,
  ].filter(Boolean);

  // Determine breaking flag
  const breaking = draft.weatherMetadata.severity === 'Extreme' || draft.weatherMetadata.urgency === 'Immediate';
  const featured = draft.storyKey === 'flood-warning__lake-il__2026-09-27'; // top story

  // Extract state from areaDesc for the state field
  const stateMatch = draft.weatherMetadata.areaDesc?.match(/,\s*([A-Z]{2})/);
  const state = stateMatch ? stateMatch[1] : undefined;

  return `---
slug: "${draft.slug}"
title: "${escapeYaml(draft.title)}"
description: "${escapeYaml(draft.description)}"
category: weather
author: "${escapeYaml(draft.author)}"
publishedAt: ${publishedAt}
updatedAt: ${updatedAt}
image: "${heroPath}"
imageAlt: "${escapeYaml(heroAlt)}"
sourceName: "${escapeYaml(draft.sourceName)}"
sourceUrl: "${draft.sourceUrl}"
tags: [${tags.map((t) => `"${escapeYaml(t)}"`).join(', ')}]
${state ? `state: "${state}"\n` : ''}breaking: ${breaking}
featured: ${featured}
views: ${Math.floor(Math.random() * 5000) + 1000}
---

${finalBody}
`;
}

function escapeYaml(s) {
  return String(s || '').replace(/"/g, '\\"').replace(/\n/g, ' ');
}

main().catch((err) => {
  console.error(`[publish-5a] FATAL: ${err.message}`);
  console.error(err.stack);
  process.exit(1);
});
